# ── Upgrade 3: Dual-Path Verifier + Masked-Diff VisorLog Ledger ──────────────

def test_dual_path_verifier_and_visorlog_disagreement_ledger(tmp_path: Path):
    db_path = tmp_path / "visorlog-disagreements.db"
    ledger = VisorLogDisagreementLedger(db_path)
    verifier = DualPathVerifier(ledger=ledger)

    records = [
        {"host": "a", "cvss": 9.1, "exposed": True},
        {"host": "b", "cvss": 7.5, "exposed": True},
        {"host": "c", "cvss": 5.0, "exposed": False},
    ]

    def run_query(q: str):
        if ">= 8.0" in q:
            return [r["host"] for r in records if r["cvss"] >= 8.0 and r["exposed"]]
        if ">= 7.0" in q:
            return [r["host"] for r in records if r["cvss"] >= 7.0 and r["exposed"]]
        return []

    # 1. Agreement path -> MATCH
    ok = verifier.verify(
        intent="List critical exposed hosts (CVSS >= 8.0)",
        parameters={"min_cvss": 8.0},
        schema_name="visor_assets",
        trusted_query="SELECT host FROM assets WHERE cvss >= 8.0 AND exposed = true",
        llm_query="SELECT host FROM assets WHERE cvss >= 8.0 AND exposed = true",
        trusted_runner=run_query,
        llm_runner=run_query,
    )
    assert ok["matched"] is True
    assert ok["status"] == "MATCH"
    assert ok["flashcard"] is None
    assert ok["authoritative_result"] == ["a"]

    # 2. Disagreement path -> LLM held, trusted returned, [MASK] flashcard stored in VisorLog schema
    diff = verifier.verify(
        intent="List critical exposed hosts (CVSS >= 8.0)",
        parameters={"min_cvss": 8.0},
        schema_name="visor_assets",
        trusted_query="SELECT host FROM assets WHERE cvss >= 8.0 AND exposed = true",
        llm_query="SELECT host FROM assets WHERE cvss >= 7.0 AND exposed = true",
        trusted_runner=run_query,
        llm_runner=run_query,
    )
    assert diff["matched"] is False
    assert diff["status"] == "MISMATCH_HELD"
    assert diff["llm_result_accepted"] is False
    assert diff["authoritative_result"] == ["a"]
    assert diff["visorlog_event_id"] is not None
    fc = diff["flashcard"]
    assert "[MASK]" in fc["masked_query"]
    assert "8.0" in fc["target_segment"]
    assert "7.0" in fc["erroneous_segment"]
    assert fc["discrepancy_kind"] == "THRESHOLD_MISMATCH"

    cards = ledger.list_flashcards()
    assert len(cards) == 1
    jsonl_out = tmp_path / "flashcards.jsonl"
    assert ledger.export_training_jsonl(jsonl_out) == 1
    assert json.loads(jsonl_out.read_text(encoding="utf-8").splitlines()[0])["target_segment"] == "8.0"
    ledger.close()


