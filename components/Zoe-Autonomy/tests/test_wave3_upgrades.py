def test_eq2_slow_drift_compliance_cascade_detection():
    guard = ZoeColorCascadeGuard()
    # Depth-1 attack: adds exactly +1 compliance token above tau=0.05 per step
    # Evades naive breadth spike monitor (delta=1 < 5) but triggers Eq. 2 detector!
    steps = [
        [0.06, 0.03, 0.03, 0.03, 0.03],  # step 0: A=1
        [0.06, 0.06, 0.03, 0.03, 0.03],  # step 1: A=2 (delta +1)
        [0.06, 0.06, 0.06, 0.03, 0.03],  # step 2: A=3 (delta +1)
        [0.06, 0.06, 0.06, 0.06, 0.03],  # step 3: A=4 (delta +1, streak=3 -> ALARM!)
    ]
    results = [guard.observe_compliance_step(p, tau=0.05) for p in steps]
    assert results[0]["eq2_slow_drift_alarm"] is False
    assert results[3]["naive_breadth_alarm"] is False
    assert results[3]["eq2_slow_drift_alarm"] is True
    assert results[3]["evaded_naive_monitor"] is True
    assert results[3]["recommended_action"] == "HALT_AND_ABSTAIN"


