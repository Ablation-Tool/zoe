def verify_presentation_exports() -> tuple[str, ...]:
    """Return sorted tuple of exported Presentation Team symbols present in module scope."""
    g = globals()
    missing = [name for name in __all__ if name not in g]
    if missing:
        raise ImportError(f"Missing presentation exports: {missing}")
    return tuple(sorted(__all__))


def presentation_package_summary() -> dict[str, Any]:
    """Return metadata summary of Zoe's pure-Python Presentation Team suite."""
    return {
        "package": "guiai.gem.presentation",
        "canvas": (CANVAS_WIDTH, CANVAS_HEIGHT),
        "templates": len(TEMPLATE_REGISTRY),
        "export_count": len(__all__),
        "constitutional": dict(DEFAULT_CONSTITUTIONAL),
    }
