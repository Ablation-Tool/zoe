def _minimal_elf64() -> bytes:
    """Construct a minimal deterministic ELF64 x86_64 buffer (never executed)."""
    e_ident = b"\x7fELF\x02\x01\x01\x00" + b"\x00" * 8
    ehdr = struct.pack(
        "<16sHHIQQQIHHHHHH",
        e_ident, 2, 0x3E, 1, 0x401000, 0, 64, 0, 64, 56, 0, 64, 1, 0,
    )
    payload = b"\x00.shstrtab\x00.text\x00zoe_probe\x00"
    shdr = struct.pack("<IIQQQQIIQQ", 1, 3, 0, 0, 128, len(payload), 0, 0, 1, 0)
    return ehdr + shdr + payload


def _sample_fes(spec_id: str = "FES-ABL-UNIT") -> FunctionEngineeringSpecification:
    """Create a valid Function Engineering Specification for EDDBMS bridge tests."""
    return FunctionEngineeringSpecification(
        spec_id=spec_id,
        title="Ablation Unit Test Pod",
        objective="Verify read-only static analysis attachment",
        owner="Zoe Engineering Collective",
        constraints={"loopback_only": True},
        target_properties={"advisory_only": True},
        geometric_requirements={"canvas": [640, 400]},
    )


def test_constitutional_metadata_and_report_guards() -> None:
    meta = constitutional_metadata()
    assert meta["contract"] == ABLATION_BRIDGE_CONTRACT
    assert meta["advisory_only"] is True
    assert meta["read_only"] is True
    assert meta["external_actions"] == 0
    assert meta["tokens_used"] == 0
    assert meta["cloud_cost_usd"] == 0.0
    assert meta["loopback_only"] is True
    assert meta["sentience_claimed"] is False
    assert ATTRIBUTION_TEXT in meta["attribution"]

    with pytest.raises(ValueError):
        constitutional_metadata("action")
    with pytest.raises(ConstitutionalViolationError):
        constitutional_metadata("measurement", read_only=False)
    with pytest.raises(ConstitutionalViolationError):
        AblationAdvisoryReport(
            target_name="bad",
            target_path=None,
            target_sha256="0" * 64,
            mode="bytes",
            byte_size=0,
            tokens_used=1,
        )
    with pytest.raises(ConstitutionalViolationError):
        AblationAdvisoryReport(
            target_name="nan_entropy",
            target_path=None,
            target_sha256="0" * 64,
            mode="bytes",
            byte_size=0,
            entropy_summary={"x": float("nan")},
        )
    with pytest.raises(ConstitutionalViolationError):
        AblationAdvisoryReport(
            target_name="inf_binary",
            target_path=None,
            target_sha256="0" * 64,
            mode="binary",
            byte_size=0,
            binary_summary={"score": float("inf")},
        )
    with pytest.raises(ConstitutionalViolationError):
        AblationAdvisoryReport(
            target_name="exec_finding",
            target_path=None,
            target_sha256="0" * 64,
            mode="bytes",
            byte_size=0,
            findings=({"execute": True},),
        )
    with pytest.raises(ConstitutionalViolationError):
        AblationAdvisoryReport(
            target_name="nan_source_audit",
            target_path=None,
            target_sha256="0" * 64,
            mode="source",
            byte_size=0,
            source_audit={"ratio": float("nan")},
        )


def test_inspect_minimal_elf64_and_ai_agent_indicators() -> None:
    bridge = AblationBridge()
    elf = _minimal_elf64()
    rep = bridge.inspect_target_readonly(raw_bytes=elf, target_name="minimal.elf")
    assert rep.ok is True
    assert rep.mode == "binary"
    assert rep.arch == "x86_64"
    assert rep.target_sha256 == hashlib.sha256(elf).hexdigest()
    assert rep.entropy_summary["window_count"] >= 1
    assert rep.advisory_only is True and rep.read_only is True

    agent_buf = (
        elf
        + b"api.openai.com\x00execve\x00agent_loop\x00"
        + b'{"name": "exec_bash", "parameters": {}}\x00'
        + b"Generated by GitHub Copilot\x00"
    )
    agent_rep = bridge.inspect_target_readonly(raw_bytes=agent_buf, target_name="agent.elf")
    assert agent_rep.auditor_findings["total_findings"] >= 1
    assert len(agent_rep.findings) == agent_rep.auditor_findings["total_findings"]


def test_inspect_empty_and_corrupt_bytes_graceful() -> None:
    bridge = AblationBridge()
    for raw in (b"", b"\x00\xffDEAD\xbe\xef"):
        rep = bridge.inspect_target_readonly(raw_bytes=raw, target_name="edge.bin")
        assert rep.ok is True
        assert rep.target_sha256 == hashlib.sha256(raw).hexdigest()
        assert rep.advisory_only is True
        assert rep.read_only is True
        assert rep.external_actions == 0


def test_inspect_source_file_directory_and_in_memory_source(tmp_path: Path) -> None:
    bridge = AblationBridge()
    py_file = tmp_path / "probe.py"
    py_file.write_text("import os\ndef run(x: str) -> None:\n    os.system(x)\n", encoding="utf-8")

    file_rep = bridge.inspect_target_readonly(target_path=py_file, mode="source")
    assert file_rep.mode == "source"
    assert file_rep.source_audit is not None
    assert file_rep.source_audit["finding_count"] >= 1

    dir_rep = bridge.inspect_target_readonly(target_path=tmp_path, mode="source")
    assert dir_rep.mode == "source"
    assert dir_rep.source_audit is not None

    mem_rep = bridge.inspect_target_readonly(
        raw_bytes=b"def clean(x: int) -> int:\n    return x + 1\n",
        target_name="clean.py",
        mode="source",
    )
    assert mem_rep.mode == "source"
    assert mem_rep.source_audit is not None


def test_safety_non_execution_invalid_modes_and_home_isolation(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    fake_home = tmp_path / "fake_home"
    fake_home.mkdir()
    monkeypatch.setenv("HOME", str(fake_home))

    sentinel = tmp_path / "executed.sentinel"
    script = tmp_path / "danger.sh"
    script.write_text(f"#!/bin/sh\ntouch '{sentinel}'\n", encoding="utf-8")
    script.chmod(0o755)

    bridge = AblationBridge()
    rep = bridge.inspect_target_readonly(target_path=script)
    assert rep.advisory_only is True and rep.read_only is True
    assert not sentinel.exists()
    assert not (fake_home / ".ablation").exists()
    assert "ablation.analyzers.advisor" not in sys.modules

    with pytest.raises(FileNotFoundError):
        bridge.inspect_target_readonly(target_path=tmp_path / "missing.elf")
    with pytest.raises(ValueError):
        bridge.inspect_target_readonly(target_path=None, raw_bytes=None)
    with pytest.raises(ValueError):
        bridge.inspect_target_readonly(target_path=script, raw_bytes=b"abc")
    for bad_mode in ("advisor", "execute_live", "claude"):
        with pytest.raises(ValueError):
            bridge.inspect_target_readonly(raw_bytes=b"abc", mode=bad_mode)


def test_attach_ablation_to_eddms_and_revision_conflict() -> None:
    db = EngineeringDesignDatabase()
    rec1 = db.ingest_specification(_sample_fes())
    rep = AblationBridge().inspect_target_readonly(raw_bytes=_minimal_elf64(), target_name="fw.elf")

    rec2 = attach_ablation_to_eddms(db, rec1.general.design_id, rep, sister_name="Mono", expected_revision=1)
    assert rec2.revision == 2
    assert rec2.geometric.analysis_process_formats["ablation"]["advisory_only"] is True
    assert rec2.geometric.analysis_process_formats["ablation"]["epistemic_lane"] == "measurement"
    assert rec2.properties.structure_desc["ablation_summary"]["target_sha256"] == rep.target_sha256
    assert db.verify_integrity(rec1.general.design_id)["ok"] is True

    with pytest.raises(RevisionConflictError):
        attach_ablation_to_eddms(db, rec1.general.design_id, rep, sister_name="Mono", expected_revision=1)
    with pytest.raises(ConstitutionalViolationError):
        attach_ablation_to_eddms(
            db,
            rec1.general.design_id,
            {"advisory_only": False, "read_only": True},
            sister_name="Mono",
            expected_revision=2,
        )


