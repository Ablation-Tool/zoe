def test_kevlar_mcp_home_subdir_and_vector_filter_guards(tmp_path: Path):
    fake_home = tmp_path / "home"
    proj = fake_home / "workspace"
    ssh_dir = fake_home / ".ssh"
    aws_dir = fake_home / ".aws"
    for d in (proj, ssh_dir, aws_dir):
        d.mkdir(parents=True)
    (proj / "README.md").write_text("ok", encoding="utf-8")
    (ssh_dir / "CANARY").write_text("secret", encoding="utf-8")
    (aws_dir / "credentials").write_text("secret", encoding="utf-8")

    # Legit workspace file -> allowed
    ok = check_mcp_path_with_kevlar(str(proj / "README.md"), allowed_roots=[str(proj)], home_dir=str(fake_home))
