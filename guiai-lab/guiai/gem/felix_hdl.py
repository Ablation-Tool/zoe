from __future__ import annotations

import json
from pathlib import Path
import re

from .felix import recover_hdl_html


SOURCE_ROOTS = ("sims/lcb", "sims/star_flink")


def _safe_name(value):
    if not re.fullmatch(r"[A-Za-z0-9_@.-]+", value) or value in {".", ".."}:
        raise ValueError(f"unsafe recovered HDL filename: {value}")
    return value


def export_html_hdl(cern_root, output_root, source_roots=SOURCE_ROOTS):
    from .cern_layout import CorpusLayout
    layout = CorpusLayout(cern_root)
    cern_root = layout.root
    output_root = Path(output_root).expanduser().resolve()
    simulation_root = layout.path("sims")
    if output_root == simulation_root or simulation_root in output_root.parents:
        raise ValueError("recovered HDL output must not overwrite the simulation source tree")
    if output_root.exists() and any(output_root.iterdir()):
        raise ValueError(f"recovered HDL output directory must be new or empty: {output_root}")
    documents = []
    destinations = set()
    for source_root in source_roots:
        root = layout.path(source_root)
        if not root.is_dir():
            continue
        for path in sorted(root.rglob("*")):
            if not path.is_file() or path.suffix.lower() not in {".htm", ".html"} or "ContentFrame" not in path.name:
                continue
            try:
                recovered = recover_hdl_html(path)
            except (OSError, UnicodeError, ValueError):
                continue
            relative = layout.relative(path)
            title = Path(recovered["title"]).name
            extension = ".v" if recovered["language"] == "verilog" else ".vhd"
            if Path(title).suffix.lower() not in {".v", ".sv", ".vhd", ".vhdl"}:
                title += extension
            title = _safe_name(title)
            destination = Path(source_root) / path.parent.relative_to(root) / title
            if destination in destinations:
                destination = destination.with_name(f"{destination.stem}-{recovered['sha256'][:8]}{destination.suffix}")
            if destination in destinations:
                raise ValueError(f"duplicate recovered HDL destination: {destination}")
            destinations.add(destination)
            documents.append({
                "source": str(relative),
                "output": str(destination),
                "title": recovered["title"],
                "language": recovered["language"],
                "line_count": recovered["line_count"],
                "sha256": recovered["sha256"],
                "text": recovered["text"],
            })
    if not documents:
        raise ValueError(f"no recoverable HTML HDL found under {cern_root}")
    output_root.mkdir(parents=True, exist_ok=True)
    manifest = []
    for document in documents:
        destination = output_root / document["output"]
        destination.parent.mkdir(parents=True, exist_ok=True)
        with destination.open("x", encoding="utf-8", newline="\n") as stream:
            stream.write(document["text"])
        manifest.append({key: value for key, value in document.items() if key != "text"})
    manifest.sort(key=lambda row: row["output"])
    report = {
        "schema_version": 1,
        "instrument": "zoe-html-hdl-recovery",
        "layout": layout.kind,
        "cern_root": str(cern_root),
        "output_root": str(output_root),
        "source_roots": list(source_roots),
        "file_count": len(manifest),
        "line_count": sum(row["line_count"] for row in manifest),
        "languages": {language: sum(row["language"] == language for row in manifest) for language in sorted({row["language"] for row in manifest})},
        "files": manifest,
        "integrity": "SHA-256 is computed from recovered UTF-8 HDL text, not from the source HTML wrapper",
    }
    with (output_root / "index.json").open("x", encoding="utf-8") as stream:
        json.dump(report, stream, ensure_ascii=False, allow_nan=False, indent=2, sort_keys=True)
        stream.write("\n")
    lines = [
        "# Recovered LCB and STAR/Flink HDL",
        "",
        f"Recovered {len(manifest)} source files from {cern_root}. Original HTML artifacts were not modified.",
        "",
        "| Recovered file | Language | Lines | Original HTML | SHA-256 |",
        "|---|---|---:|---|---|",
    ]
    for row in manifest:
        lines.append(f"| `{row['output']}` | {row['language']} | {row['line_count']} | `{row['source']}` | `{row['sha256']}` |")
    lines.extend([
        "",
        "The source HTML was generated by HDL Designer. Recovery removes markup and decodes HTML entities; it does not prove synthesis, simulation, or equivalence to a particular FPGA bitstream.",
        "",
    ])
    (output_root / "INDEX.md").write_text("\n".join(lines), encoding="utf-8")
    return report
