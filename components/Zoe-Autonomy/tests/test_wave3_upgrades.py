# ── Upgrade 5: Email Allowlist + ROS Motion Deadman + VisorCAS Bloom/CAS ────

def test_email_guardrail_and_ros_motion_gate_on_actuation_policy(tmp_path: Path):
    eg = AgentEmailGuardrail(tmp_path / "email_guard.db")
    eg.set_policy(
        "zoe",
        user_id="owner",
        allowed_recipients=["security@nuclide-research.com", "@trusted.example"],
        sends_per_minute=2,
        reads_per_day=5,
    )
    assert eg.check_send("zoe", "security@nuclide-research.com", "Status")["allowed"] is True
    assert eg.check_send("zoe", "ops@trusted.example", "Alert")["allowed"] is True
    # Third send in same minute hits rate limit
    rl = eg.check_send("zoe", "security@nuclide-research.com", "Burst")
    assert rl["allowed"] is False and rl["reason"] == "rate_limit_exceeded"
    # Non-allowlisted recipient & CRLF header injection denied
    assert eg.check_send("zoe", "attacker@evil.invalid")["reason"] == "recipient_not_allowlisted"
    assert eg.check_send("zoe", "security@nuclide-research.com\r\nBcc: evil@x.org")["reason"] == "header_injection"
    assert len(eg.audit_entries()) == 5
    eg.close()

    # ROS motion gate standalone + wired into ActuationPolicy
    ro = evaluate_robotics_motion_gate({"ros_topic": "/joint_states"})
    assert ro["allowed"] is True and ro["is_motion_command"] is False

    blocked_deadman = evaluate_robotics_motion_gate(
        {"ros_topic": "/base_controller/command", "deadman_held": False, "confirmation_token": "tok-1"},
        expected_token="tok-1",
    )
    assert blocked_deadman["allowed"] is False and blocked_deadman["reason"] == "deadman_switch_not_held"

    blocked_tok = evaluate_robotics_motion_gate(
        {"ros_topic": "/base_controller/command", "deadman_held": True, "confirmation_token": "wrong"},
        expected_token="tok-1",
    )
    assert blocked_tok["allowed"] is False and blocked_tok["reason"] == "confirm_before_move_token_missing_or_invalid"

    # End-to-end ActuationPolicy dry-run vs denied physical motion
    policy = ActuationPolicy(
        root=tmp_path / "actuation",
        motion_confirmation_token="move-ok-42",
    )
    policy.enable(["hardware", "network"], owner_approved=True)
    with pytest.raises(PermissionError, match="deadman_switch_not_held"):
        policy.execute({
            "kind": "hardware",
            "device": "/dev/null",
            "payload_hex": "0102",
            "ros_topic": "/base_controller/command",
            "deadman_held": False,
        })
    dry = policy.execute({
        "kind": "hardware",
        "device": "/dev/null",
        "payload_hex": "0102",
        "ros_topic": "/base_controller/command",
        "dry_run": True,
    })
    assert dry["dry_run"] is True and dry["external_action"] is False

    # Outbound email without attached guardrail denied
    with pytest.raises(PermissionError, match="AgentEmailGuardrail"):
        policy.execute({
            "kind": "network",
            "url": "https://example.com/mail",
            "email_recipient": "anyone@example.com",
        })


