# ── Upgrade 1: 5D Continuous TrustEngine -> DualPeerSession + nina Lume ──────

def test_trust_engine_source_ceiling_and_audio_haze():
    te = TrustEngine(source_trust=0.20)
    packets = [
        {"ts": float(i) * 0.1, "size": 64 + (i % 7) * 120, "proto": 6, "dst": f"10.0.0.{i % 5}"}
        for i in range(60)
    ]
    out = te.evaluate(packets)
    assert out <= 0.20 + 1e-9, "output_trust must NEVER exceed source_trust"
    reverb_low = te.get_reverb_params()
    width_low = te.get_stereo_width()

    te.set_source_trust(0.95)
    out_high = te.evaluate(packets)
    assert out_high <= 0.95 + 1e-9
    assert out_high > out
    assert te.get_reverb_params()["delay_ms"] < reverb_low["delay_ms"]
    assert te.get_stereo_width() > width_low


def test_dual_peer_session_emits_trust_gradient_and_lume_cue():
    sess = DualPeerSession(root=str(ROOT), provider="local_cited")
