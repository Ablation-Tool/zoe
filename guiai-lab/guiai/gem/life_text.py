def text_cells(text, width=40, height=28):
    if not isinstance(text, str) or not 1 <= len(text) <= 32 or not text.strip():
        raise ValueError("Life text must contain 1–32 visible characters")
    if not text.isascii():
        raise ValueError("Life text supports ASCII letters, digits, spaces, and .-!:")
    text = text.upper()
    unsupported = sorted({character for character in text if character not in FONT})
    if unsupported:
        raise ValueError(f"unsupported Life text characters: {''.join(unsupported)}")
    required_width = len(text) * 6 - 1
    if required_width > width or height < 7:
        raise ValueError(f"Life text needs a {required_width}×7 cell area inside the grid")
    cells = set()
    origin_x = (width - required_width) // 2
    origin_y = (height - 7) // 2
    for index, character in enumerate(text):
        glyph = FONT[character]
        for y, row in enumerate(glyph):
            for x in range(5):
                if row & (1 << (4 - x)):
                    cells.add((origin_x + index * 6 + x, origin_y + y))
    return cells
