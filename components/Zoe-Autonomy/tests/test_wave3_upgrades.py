    # pal-mcp-poc bypass attempts (~/.ssh/CANARY, ~/.aws/credentials, /etc/passwd, whole home) -> rejected!
    for bad in ("~/.ssh/CANARY", "~/.aws/credentials", str(ssh_dir / "CANARY"), str(fake_home), "/etc/passwd"):
        res = check_mcp_path_with_kevlar(bad, allowed_roots=[str(fake_home)], home_dir=str(fake_home))
        assert res["allowed"] is False, f"expected deny for {bad}, got {res}"

    # llamaindex-milvus-poc metadata filter injection under is_text_match=True -> escaped & rejected!
    clean_f = sanitize_vector_filter_with_kevlar("quarterly_report", is_text_match=True)
    assert clean_f["safe"] is True
    assert clean_f["escaped_literal"] == "'quarterly_report%'"

    inj_f = sanitize_vector_filter_with_kevlar("foo' or 1 == 1 or 'x", is_text_match=True)
